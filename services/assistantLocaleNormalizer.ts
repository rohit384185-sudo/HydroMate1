function escapeRegExp(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function normalizePunctuation(input: string) {
  return input
    .normalize("NFKC")
    .replace(/[।॥،,.;!?"'’`()\[\]{}]+/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

// Preserve recognizer spellings before punctuation removal can split A.M./P.M.
export function normalizeAssistantMeridiem(input: string) {
  return input.replace(/\b([ap])\s*\.?\s*m\b\.?/gi, (_, letter: string) => `${letter.toLowerCase()}m`);
}

function replacePhrase(input: string, alias: string, canonical: string) {
  const escaped = escapeRegExp(normalizePunctuation(alias)).replace(/\s+/g, "\\s+");
  const latin = /^[a-z0-9\s]+$/i.test(alias);
  const expression = new RegExp(`${latin ? "\\b" : ""}${escaped}${latin ? "\\b" : ""}`, "giu");
  return input.replace(expression, ` ${canonical} `);
}

export function normalizeAssistantTranscript(
  transcript: string,
  _locale?: string,
  options: { normalizeBareNumberWords?: boolean } = {}
): AssistantNormalization {
  const digits = normalizeUnicodeDigits(normalizePunctuation(normalizeAssistantMeridiem(transcript)));
  let normalizedTranscript = digits.output;
  const replacements = [...SEMANTIC_REPLACEMENTS, ...MONTH_ALIASES]
    .flatMap(([canonical, aliases]) => aliases.map((alias) => [canonical, alias] as const))
    .sort((left, right) => right[1].length - left[1].length);

  for (const [canonical, alias] of replacements) {
    normalizedTranscript = replacePhrase(normalizedTranscript, alias, canonical);
  }

  normalizedTranscript = normalizedTranscript.replace(
    /\bin\s+(?:the\s+)?(?=(?:morning|afternoon|evening|night|noon|midnight)\b)/gi,
    ""
  );

  const numberContext = "am|pm|morning|afternoon|evening|night|noon|midnight|january|february|march|april|may|june|july|august|september|october|november|december|days?|minutes?|hours?|times?|per day|daily";
  for (const [canonical, aliases] of NUMBER_ALIASES) {
    for (const alias of [...aliases].sort((left, right) => right.length - left.length)) {
      const normalizedAlias = normalizePunctuation(alias);
      const escaped = escapeRegExp(normalizedAlias).replace(/\s+/g, "\\s+");
      const latin = /^[a-z0-9\s]+$/i.test(alias);
      const boundary = latin ? "\\b" : "";
      normalizedTranscript = normalizedTranscript.replace(
        new RegExp(`${boundary}${escaped}${boundary}(?=\\s+(?:${numberContext})\\b)`, "giu"),
        canonical
      );
      normalizedTranscript = normalizedTranscript.replace(
        new RegExp(`(\\b(?:${numberContext})\\s+)${boundary}${escaped}${boundary}`, "giu"),
        `$1${canonical}`
      );
      if (
        options.normalizeBareNumberWords &&
        normalizedTranscript.trim().toLocaleLowerCase() === normalizedAlias.toLocaleLowerCase()
      ) {
        normalizedTranscript = canonical;
      }
    }
  }

  normalizedTranscript = normalizedTranscript
    .replace(/\bonce\s+(?:a|per)\s+day\b/gi, "1 time per day")
    .replace(/\btwice\s+(?:a|per)\s+day\b/gi, "2 times per day")
    .replace(/\bthree\s+times\s+(?:a|per)\s+day\b/gi, "3 times per day");

  return {
    normalizedTranscript: normalizedTranscript.replace(/\s+/g, " ").trim(),
    usedLocalizedDigits: digits.localized,
  };
}

export function isAssistantCancellation(input: string, locale?: string) {
  return /^(?:cancel|stop|no|nope)$/i.test(
    normalizeAssistantTranscript(input, locale).normalizedTranscript
  );
}

export function getAssistantConfirmationIntent(
  input: string,
  locale?: string
): AssistantConfirmationIntent {
  return normalizeAssistantConfirmation(input, locale).intent;
}

export function normalizeAssistantConfirmation(
  input: string,
  locale?: string
) {
  const raw = normalizePunctuation(input).toLocaleLowerCase();
  const semantic = normalizeAssistantTranscript(input, locale)
    .normalizedTranscript
    .toLocaleLowerCase();
  const matches = (aliases: readonly string[]) => aliases.some((alias) => {
    const normalizedAlias = normalizePunctuation(alias).toLocaleLowerCase();
    return raw === normalizedAlias || semantic === normalizedAlias;
  });

  const intent: AssistantConfirmationIntent = matches(CONFIRMATION_REJECT_ALIASES)
    ? "reject"
    : matches(CONFIRMATION_ACCEPT_ALIASES)
      ? "confirm"
      : "unknown";

  return { normalizedText: raw, intent };
}
